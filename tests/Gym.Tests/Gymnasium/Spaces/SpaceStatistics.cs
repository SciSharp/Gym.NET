        /// <summary>The chi-square critical value at <see cref="Alpha"/> (<c>scipy.stats.chi2.isf(ALPHA, df=df)</c>).</summary>
        /// <param name="degreesOfFreedom">The degrees of freedom, 1 to 300.</param>
        /// <returns>The critical value.</returns>
        /// <exception cref="ArgumentOutOfRangeException">Thrown for degrees of freedom outside the recorded table.</exception>
        internal static double Chi2Isf(long degreesOfFreedom) {
            if (degreesOfFreedom < 1 || degreesOfFreedom > Chi2Critical.Length)
                throw new ArgumentOutOfRangeException(nameof(degreesOfFreedom), degreesOfFreedom, "Only df 1..300 are recorded.");
            return Chi2Critical[degreesOfFreedom - 1];
        }

        /// <summary>
        ///     The p-value of the one-sample Kolmogorov-Smirnov test of <paramref name="sample"/> against <paramref name="cdf"/>
        ///     (<c>scipy.stats.kstest(sample, cdf)[1]</c>, asymptotically).
        /// </summary>
        /// <param name="sample">The sample.</param>
        /// <param name="cdf">The distribution's cumulative distribution function.</param>
        /// <returns>The p-value.</returns>
        internal static double KsTestPValue(double[] sample, Func<double, double> cdf) {
            double[] sorted = sample.OrderBy(x => x).ToArray();
            int n = sorted.Length;
            double d = 0;
            for (int i = 0; i < n; i++) {
                double f = cdf(sorted[i]);
                d = Math.Max(d, Math.Max((i + 1.0) / n - f, f - (double)i / n));
            }

            double lambda = (Math.Sqrt(n) + 0.12 + 0.11 / Math.Sqrt(n)) * d;
            if (lambda < 1e-3)
                return 1.0;
            double sum = 0;
            for (int k = 1; k <= 100; k++)
                sum += (k % 2 == 1 ? 2.0 : -2.0) * Math.Exp(-2.0 * k * k * lambda * lambda);
            return Math.Clamp(sum, 0.0, 1.0);
        }

        /// <summary>The standard normal CDF (<c>scipy.stats.norm.cdf</c>).</summary>
        /// <param name="x">The point.</param>
        /// <returns>P(X &lt;= x).</returns>
        internal static double NormalCdf(double x) => 0.5 * Erfc(-x / Math.Sqrt(2.0));

        /// <summary>The exponential(1) CDF (<c>scipy.stats.expon.cdf</c>).</summary>
        /// <param name="x">The point.</param>
        /// <returns>P(X &lt;= x).</returns>
        internal static double ExponCdf(double x) => x <= 0 ? 0.0 : 1.0 - Math.Exp(-x);

        /// <summary>The geometric PMF on 1, 2, ... (<c>scipy.stats.geom(p).pmf(k)</c>).</summary>
        /// <param name="p">The success probability.</param>
        /// <param name="k">The trial of the first success.</param>
        /// <returns>P(X = k).</returns>
        internal static double GeomPmf(double p, long k) => k < 1 ? 0.0 : Math.Pow(1.0 - p, k - 1) * p;

        /// <summary>The complementary error function, by Numerical Recipes' Chebyshev fit (relative error below 1.2e-7).</summary>
        /// <param name="x">The point.</param>
        /// <returns>erfc(x).</returns>
        private static double Erfc(double x) {
            double z = Math.Abs(x);
            double t = 1.0 / (1.0 + 0.5 * z);
            double r = t * Math.Exp(-z * z - 1.26551223 + t * (1.00002368 + t * (0.37409196 + t * (0.09678418 + t * (-0.18628806 + t * (0.27886807 +
                       t * (-1.13520398 + t * (1.48851587 + t * (-0.82215223 + t * 0.17087277)))))))));
            return x >= 0 ? r : 2.0 - r;
        }
