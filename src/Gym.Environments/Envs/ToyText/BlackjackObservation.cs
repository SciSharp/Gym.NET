#nullable enable
using System;
using Gym.Utils;
using NumSharp;

namespace Gym.Environments.Envs.ToyText {
    /// <summary>
    ///     A Blackjack observation read by name (DR-13): Gymnasium's <c>(player_sum, dealer_card, usable_ace)</c>, each item a
    ///     0-d int64 array (DR-08). <see cref="BlackjackEnv"/> returns Gym.NET's generic tuple, <see langword="object"/>?[] (what
    ///     its <c>Tuple</c> observation space samples and every space tool reads); assigning one to this record converts it:
    ///     <c>BlackjackObservation obs = env.Reset().Observation;</c>.
    /// </summary>
    /// <remarks>
    ///     The conversion shares the arrays rather than copying them, so disposing the record's arrays disposes the
    ///     observation's. Equality and <c>repr</c> are Python's tuple's (generated by <see cref="GymTupleAttribute"/>), and the
    ///     record is itself a tuple to the spaces: <c>env.ObservationSpace.Contains(obs)</c> holds for a record converted from
    ///     an observation.
    /// </remarks>
    /// <param name="PlayerSum">The player's total, an ace counted as 11 when that keeps the total at 21 or under (up to 31 after a busting hit).</param>
    /// <param name="DealerCard">The dealer's face-up card: 1 for an ace, 2 to 10 for the others (a jack, queen or king is 10).</param>
    /// <param name="UsableAce">1 when the player's total counts an ace as 11, else 0.</param>
    [GymTuple]
    public partial record BlackjackObservation(NDArray PlayerSum, NDArray DealerCard, NDArray UsableAce) : IDisposable {
        /// <summary>
        ///     Disposes the three arrays. A record converted from an observation shares that observation's arrays, so this
        ///     releases the observation too: dispose one or the other, once.
        /// </summary>
        public void Dispose() {
            PlayerSum?.Dispose();
            DealerCard?.Dispose();
            UsableAce?.Dispose();
        }
    }
}
